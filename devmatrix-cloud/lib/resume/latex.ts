import { TEMPLATES } from './templates';
import { dateText, entryHas, hasContent, type Design, type Resume, type Section } from './types';

const esc = (s: string) =>
  s.replace(/\\/g, '\u0000').replace(/([&%$#_{}])/g, '\\$1').replace(/~/g, '\\textasciitilde{}').replace(/\^/g, '\\textasciicircum{}')
    .replace(/\u0000/g, '\\textbackslash{}')
    .replace(/—/g, '---').replace(/–/g, '--').replace(/[“”]/g, "''").replace(/[‘’]/g, "'").replace(/•/g, '\\textbullet{}')
    .replace(/…/g, '\\ldots{}').replace(/→/g, '$\\rightarrow$');
const url = (u: string) => (/^[a-z]+:/i.test(u) ? u : `https://${u}`).replace(/([%#])/g, '\\$1');
const hex6 = (h: string) => h.replace('#', '').toUpperCase().padEnd(6, '0').slice(0, 6);
const b64 = (s: string) => btoa(unescape(encodeURIComponent(s)));

function headingFormat(h: string) {
  switch (h) {
    case 'caps': return '\\titleformat{\\section}{\\normalsize\\bfseries\\color{accent}\\MakeUppercase}{}{0em}{}';
    case 'bar': return '\\titleformat{\\section}{\\large\\bfseries}{}{0em}{\\textcolor{accent}{\\rule{3pt}{1.1ex}}\\hspace{6pt}}';
    case 'plain': return '\\titleformat{\\section}{\\normalsize\\bfseries\\color{accent}}{}{0em}{}';
    case 'slash': return '\\titleformat{\\section}{\\normalsize\\bfseries\\ttfamily}{}{0em}{\\textcolor{accent}{//}~}';
    default: return '\\titleformat{\\section}{\\large\\bfseries\\scshape}{}{0em}{}[\\vspace{-2pt}\\titlerule]';
  }
}

function body(s: Section): string {
  const out: string[] = [];
  if (s.kind === 'summary') out.push(esc(s.text ?? ''));
  else if (s.kind === 'list') out.push('\\begin{itemize}', ...(s.items ?? []).filter((i) => i.trim()).map((i) => `  \\item ${esc(i)}`), '\\end{itemize}');
  else if (s.kind === 'skills') {
    for (const g of s.groups ?? []) if (g.label.trim() || g.items.trim()) out.push(`\\noindent${g.label.trim() ? `\\textbf{${esc(g.label.trim())}:} ` : ''}${esc(g.items)}\\par`);
  } else {
    for (const e of (s.entries ?? []).filter(entryHas)) {
      const p = e.primary.trim() || e.secondary.trim();
      if (e.primary.trim() && (e.secondary.trim() || e.location.trim())) out.push(`\\cvEntry{${esc(p)}}{${esc(dateText(e))}}{${esc(e.secondary)}}{${esc(e.location)}}`);
      else out.push(`\\cvEntryOne{${esc(p)}}{${esc(dateText(e))}}`);
      const bl = e.bullets.filter((x) => x.trim());
      if (bl.length) out.push('\\begin{itemize}', ...bl.map((x) => `  \\item ${esc(x)}`), '\\end{itemize}');
      out.push('\\vspace{3pt}');
    }
  }
  return out.join('\n');
}

export function toLatex(r: Resume, d: Design): string {
  const T = TEMPLATES[d.template];
  const pt = d.baseSize < 10.5 ? 10 : d.baseSize < 11.5 ? 11 : 12;
  const b = r.basics;
  const contact = [
    b.phone.trim() && esc(b.phone.trim()),
    b.email.trim() && `\\href{mailto:${b.email.trim()}}{${esc(b.email.trim())}}`,
    b.location.trim() && esc(b.location.trim()),
    ...b.links.filter((l) => l.label.trim() || l.url.trim()).map((l) => (l.url.trim() ? `\\href{${url(l.url.trim())}}{${esc(l.label.trim() || l.url.trim())}}` : esc(l.label.trim()))),
  ].filter(Boolean).join(' \\,|\\, ');
  const family = T.font === 'sans' ? '\\renewcommand{\\familydefault}{\\sfdefault}' : T.font === 'mono' ? '\\renewcommand{\\familydefault}{\\ttdefault}' : '';
  const lead = T.header === 'center' ? '\\begin{center}' : '\\begin{flushleft}';
  const end = T.header === 'center' ? '\\end{center}' : '\\end{flushleft}';
  const secs = r.sections.filter((s) => s.visible && hasContent(s));

  const lines = [
    `% Generated by CV Studio. Template: ${T.label}. Compiles with pdfLaTeX on a stock TeX Live / Overleaf.`,
    ...(T.columns === 2 ? ['% Note: the sidebar template is exported as a single column here; the PDF export keeps the two-column design.'] : []),
    `\\documentclass[${pt}pt,${d.paper === 'a4' ? 'a4paper' : 'letterpaper'}]{article}`,
    '\\usepackage[T1]{fontenc}', '\\usepackage{lmodern}', family,
    `\\usepackage[margin=${(d.margin / 72).toFixed(2)}in]{geometry}`,
    '\\usepackage[dvipsnames]{xcolor}', `\\definecolor{accent}{HTML}{${hex6(d.accent)}}`,
    '\\usepackage{enumitem}', '\\usepackage{titlesec}',
    '\\usepackage[colorlinks=true,urlcolor=accent,linkcolor=accent]{hyperref}',
    `\\hypersetup{pdftitle={${esc(b.name || 'Resume')} - Resume},pdfauthor={${esc(b.name)}}}`,
    '\\pagestyle{empty}', '\\setlength{\\parindent}{0pt}', '\\raggedbottom',
    `\\renewcommand{\\baselinestretch}{${(d.lineHeight / 1.2).toFixed(2)}}`,
    '\\setlist[itemize]{leftmargin=1.1em,itemsep=1pt,topsep=2pt,parsep=0pt}',
    headingFormat(T.heading), '\\titlespacing*{\\section}{0pt}{10pt}{4pt}',
    '\\newcommand{\\cvEntry}[4]{\\noindent\\textbf{#1}\\hfill #2\\par\\noindent\\textit{#3}\\hfill\\textit{#4}\\par}',
    '\\newcommand{\\cvEntryOne}[2]{\\noindent\\textbf{#1}\\hfill #2\\par}',
    '', '\\begin{document}', '',
    lead, `{\\Huge\\bfseries${T.accentName ? '\\color{accent}' : ''} ${esc(b.name || 'Your Name')}}\\\\[3pt]`,
    ...(b.title.trim() ? [`{\\large ${esc(b.title)}}\\\\[3pt]`] : []),
    contact, end, '',
    ...secs.flatMap((s) => [`\\section{${esc(s.title)}}`, body(s), '']),
    '\\end{document}', '',
    `% CVSTUDIO-DATA: ${b64(JSON.stringify({ resume: r, design: d }))}`,
  ];
  return lines.filter((l) => l !== undefined).join('\n');
}
